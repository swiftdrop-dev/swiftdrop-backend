CREATE TABLE public.parcel_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id VARCHAR(64) NOT NULL,
    courier_id VARCHAR(64) NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL,
    unassigned_at TIMESTAMPTZ,
    changed_by VARCHAR(128),
    reason TEXT,
    CONSTRAINT fk_parcel_assignments_parcel
        FOREIGN KEY (parcel_id) REFERENCES public.parcels (id),
    CONSTRAINT chk_parcel_assignments_time_range
        CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);

CREATE INDEX idx_parcel_assignments_courier_assigned_at
    ON public.parcel_assignments (courier_id, assigned_at);

CREATE UNIQUE INDEX uq_parcel_assignments_one_active_per_parcel
    ON public.parcel_assignments (parcel_id)
    WHERE unassigned_at IS NULL;
