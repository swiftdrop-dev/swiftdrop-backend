CREATE TABLE public.parcel_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id VARCHAR(64) NOT NULL,
    previous_status VARCHAR(32) NOT NULL,
    new_status VARCHAR(32) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    actor_id VARCHAR(128) NOT NULL,
    failure_reason TEXT,
    CONSTRAINT fk_parcel_status_history_parcel
        FOREIGN KEY (parcel_id) REFERENCES public.parcels (id)
);

CREATE INDEX idx_parcel_status_history_parcel_changed_at
    ON public.parcel_status_history (parcel_id, changed_at, id);
